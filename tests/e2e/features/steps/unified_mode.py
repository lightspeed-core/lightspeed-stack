@given(
    "lightspeed-stack is started with --synthesized-config-output set to a custom path"
)
def start_with_custom_synthesis_output(context: Context) -> None:
    """Launch a short-lived local service with a custom synthesis output path.

    The flag only affects library-mode in-process synthesis, and the running
    containers cannot be restarted with different CLI args — so this step
    always uses the library-mode variant of the active fixture, copied to a
    scratch directory with ``service.port`` rewritten to avoid clashing with
    the running stack. The subprocess synthesizes during app startup; the
    following Then steps poll for the file, and the process is killed on
    scenario cleanup.
    """
    active_basename = _active_config_path().name
    fixture_basename = Path(
        getattr(context, "feature_config", "")
        or "lightspeed-stack-unified-providers.yaml"
    ).name
    base = Path(
        getattr(context, "lightspeed_stack_config_directory", "")
        or "tests/e2e/configuration"
    )
    library_fixture = base / "library-mode" / fixture_basename
    if not library_fixture.is_file():
        library_fixture = _config_dir(context) / fixture_basename
    assert library_fixture.is_file(), f"no library-mode fixture for {active_basename}"

    scratch = Path(tempfile.mkdtemp(prefix="lcore-e2e-synthout-"))
    context.add_cleanup(lambda: shutil.rmtree(scratch, ignore_errors=True))

    config = _load_yaml(library_fixture)
    config.setdefault("service", {})["port"] = 8099
    scratch_config = scratch / "lightspeed-stack.yaml"
    with open(scratch_config, "w", encoding="utf-8") as f:
        yaml.safe_dump(config, f)

    custom_output = scratch / "custom-run.yaml"
    process = subprocess.Popen(  # pylint: disable=consider-using-with
        [
            sys.executable,
            str(Path("src/lightspeed_stack.py").resolve()),
            "-c",
            str(scratch_config),
            "--synthesized-config-output",
            str(custom_output),
        ],
        cwd=str(scratch),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    context.custom_output_path = custom_output
    context.custom_output_scratch = scratch
    context.custom_output_process = process

    def _kill() -> None:
        if process.poll() is None:
            process.kill()
            process.wait(timeout=10)

    context.add_cleanup(_kill)


@then("the synthesized run.yaml is written to the custom output path")
def custom_output_written(context: Context) -> None:
    """Poll for the custom-path synthesis output and validate it parses."""
    custom_output = Path(context.custom_output_path)
    process = context.custom_output_process
    deadline = time.monotonic() + CUSTOM_OUTPUT_POLL_SECONDS
    while time.monotonic() < deadline:
        if custom_output.is_file() and custom_output.stat().st_size > 0:
            break
        if process.poll() is not None and not custom_output.is_file():
            out = process.stdout.read() if process.stdout else ""
            raise AssertionError(
                f"service exited (rc={process.returncode}) before writing the "
                f"custom synthesis output.\n{out[-2000:]}"
            )
        time.sleep(0.5)
    assert custom_output.is_file(), (
        f"custom synthesis output {custom_output} did not appear within "
        f"{CUSTOM_OUTPUT_POLL_SECONDS}s"
    )
    assert isinstance(_load_yaml(custom_output), dict)
    context.synthesized_run_yaml_path = custom_output


@then("the default synthesized run.yaml path does not exist")
def default_output_absent(context: Context) -> None:
    """Assert the default synthesis location was not used (override took effect)."""
    scratch = Path(context.custom_output_scratch)
    default_path = scratch / ".generated" / "run.yaml"
    assert (
        not default_path.exists()
    ), f"default synthesis path {default_path} exists despite the override"


