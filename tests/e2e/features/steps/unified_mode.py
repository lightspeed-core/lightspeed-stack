"""Step definitions for the unified-mode e2e features (LCORE-2343).

Covers configuration validation, legacy-to-unified migration, and run.yaml
synthesis for the five ``unified-mode-*.feature`` files.

Design rules (from the LCORE-2343 planning notes):

- Validation, migration, and synthesis steps operate on the **on-disk**
  configuration artifacts — never the live service. "The active
  configuration" is the repo-root ``lightspeed-stack.yaml`` copy that
  ``configure_service`` applied.
- Migration and synthesis run the real CLIs as subprocesses — exactly the
  surface the server entrypoint and operators use — and assertions parse
  the produced YAML (data equality, never byte comparison).
- The synthesis-log step is mode-aware: in server mode the synthesis
  evidence is emitted by the llama-stack container (entrypoint + CLI), not
  the lightspeed-stack container the Gherkin names; the scenario's intent
  (R10: the synthesized path is logged at startup) is asserted against the
  container that actually synthesizes.
"""

import difflib
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import Any, Optional

import yaml
from behave import given, step, then, when  # pyright: ignore
from behave.runner import Context

# Generated by the --migrate-config step; matches the .gitignore entry.
MIGRATED_CONFIG_BASENAME = "lightspeed-stack-unified-migrated.yaml"
# Legacy half of "the legacy migration fixture pair"; its run.yaml half is
# the repo-root run.yaml the CI harness materializes.
MIGRATION_PAIR_LCS_BASENAME = "lightspeed-stack-legacy-for-migration.yaml"

CLI_TIMEOUT_SECONDS = 120
CUSTOM_OUTPUT_POLL_SECONDS = 60


def _mode_subdir(context: Context) -> str:
    """Return the mode fixture subdirectory name for the current harness mode."""
    return "library-mode" if context.is_library_mode else "server-mode"


def _config_dir(context: Context) -> Path:
    """Resolve the active fixture directory, mode subdir included when present.

    Mirrors ``configure_service``'s resolution so files referenced by name in
    Gherkin (fixture pairs, migrated output) land where that step finds them.
    """
    base = Path(
        getattr(context, "lightspeed_stack_config_directory", "")
        or "tests/e2e/configuration"
    )
    mode_base = base / _mode_subdir(context)
    return mode_base if mode_base.is_dir() else base


def _active_config_path() -> Path:
    """Return the on-disk active configuration (the applied repo-root copy)."""
    return Path("lightspeed-stack.yaml")


def _run_cli(
    args: list[str], cwd: Optional[Path] = None
) -> subprocess.CompletedProcess:
    """Run a repo CLI as a subprocess, capturing output, never raising."""
    return subprocess.run(
        [sys.executable, *args],
        cwd=str(cwd) if cwd else None,
        capture_output=True,
        text=True,
        timeout=CLI_TIMEOUT_SECONDS,
        check=False,
    )


def _load_yaml(path: Path) -> Any:
    """Parse a YAML file."""
    with open(path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def _native_override(config_path: Path) -> dict[str, Any]:
    """Extract llama_stack.config.native_override from a config file."""
    config = _load_yaml(config_path)
    override = ((config.get("llama_stack") or {}).get("config") or {}).get(
        "native_override"
    )
    assert override, f"{config_path} carries no llama_stack.config.native_override"
    return override


def _synthesized(context: Context) -> Path:
    """Return the synthesized run.yaml path recorded by an earlier step."""
    path = getattr(context, "synthesized_run_yaml_path", None)
    assert path, "no synthesis step ran before this assertion"
    return Path(path)


# ---------------------------------------------------------------------------
# Validation (unified-mode-validation.feature)
# ---------------------------------------------------------------------------


@when("configuration validation is attempted for the active configuration")
def attempt_configuration_validation(context: Context) -> None:
    """Validate the on-disk active configuration via the service CLI.

    Runs ``lightspeed_stack.py --dump-configuration -c lightspeed-stack.yaml``
    as a black-box subprocess: ``main()`` loads (and thereby validates) the
    configuration before any dump handling, so a Pydantic validation failure
    surfaces on stderr with a non-zero exit code. cwd is the repo root so the
    invalid fixtures' ``library_client_config_path: run.yaml`` resolves to the
    harness-materialized run.yaml and the captured failure is the intended
    cross-field error, not a file-not-found.
    """
    result = _run_cli(
        [
            "src/lightspeed_stack.py",
            "--dump-configuration",
            "-c",
            str(_active_config_path()),
        ]
    )
    context.validation_returncode = result.returncode
    context.validation_output = result.stdout + result.stderr
    assert result.returncode != 0, (
        "expected the active configuration to fail validation, but the load "
        f"succeeded (rc=0). Output:\n{context.validation_output}"
    )


@then("the validation error contains {text}")
def validation_error_contains(context: Context, text: str) -> None:
    """Assert the captured validation failure mentions the given text."""
    output = getattr(context, "validation_output", None)
    assert output is not None, "no validation attempt ran before this assertion"
    assert (
        text.strip() in output
    ), f"validation error does not contain {text!r}. Full output:\n{output}"


