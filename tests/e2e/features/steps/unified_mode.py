@step("the active unified configuration is synthesized to run.yaml")
def synthesize_active_configuration(context: Context) -> None:
    """Synthesize a run.yaml from the on-disk unified configuration.

    Runs the config CLI exactly as the server entrypoint does (unified
    auto-detection dispatches to ``synthesize_to_file``, which also gives the
    0600 output mode). Source precedence: the migrated config when the
    migration step ran in this scenario, else the active on-disk config.
    When the custom-output service step ran instead, this step is a
    pass-through — the service subprocess performs the synthesis.
    """
    if getattr(context, "custom_output_path", None):
        return

    source = getattr(context, "migrated_config_path", None) or _active_config_path()
    scratch = Path(tempfile.mkdtemp(prefix="lcore-e2e-synthesis-"))
    context.add_cleanup(lambda: shutil.rmtree(scratch, ignore_errors=True))
    output = scratch / "run.yaml"

    result = _run_cli(
        ["src/llama_stack_configuration.py", "-c", str(source), "-o", str(output)]
    )
    assert result.returncode == 0 and output.is_file(), (
        f"synthesis CLI failed (rc={result.returncode}) for {source}.\n"
        f"stdout:\n{result.stdout}\nstderr:\n{result.stderr}"
    )
    context.synthesized_run_yaml_path = output


@then(
    "the synthesized run.yaml parses to the same data as the legacy migration fixture run.yaml"
)
def synthesized_round_trips(context: Context) -> None:
    """Assert migrate-then-synthesize reproduces the pair's run.yaml (data equality)."""
    synthesized = _load_yaml(_synthesized(context))
    original = _load_yaml(
        getattr(context, "migration_pair_run_yaml", None) or Path("run.yaml")
    )
    if synthesized != original:
        diff = "\n".join(
            difflib.unified_diff(
                yaml.dump(original, sort_keys=True).splitlines(),
                yaml.dump(synthesized, sort_keys=True).splitlines(),
                fromfile="pair run.yaml",
                tofile="synthesized",
                lineterm="",
            )
        )
        raise AssertionError(f"round-trip data mismatch:\n{diff}")


@then(
    "the synthesized run.yaml contains the native_override scalar value for safety.excluded_categories"
)
def synthesized_scalar_override(context: Context) -> None:
    """Assert the override's scalar replaced the baseline value at that key (R5)."""
    override_value = _native_override(_active_config_path())["safety"][
        "excluded_categories"
    ]
    synthesized = _load_yaml(_synthesized(context))
    actual = (synthesized.get("safety") or {}).get("excluded_categories")
    assert actual == override_value, (
        f"safety.excluded_categories is {actual!r}, expected the "
        f"native_override value {override_value!r}"
    )
    baseline = _load_yaml(Path("run.yaml"))
    baseline_value = (baseline.get("safety") or {}).get("excluded_categories")
    assert baseline_value != override_value, (
        "fixture and baseline agree on safety.excluded_categories — the "
        "replacement assertion would be vacuous"
    )


@then("the synthesized run.yaml contains exactly the native_override list for apis")
def synthesized_list_override(context: Context) -> None:
    """Assert the override list replaced the baseline's apis wholesale (R5)."""
    override_list = _native_override(_active_config_path())["apis"]
    synthesized = _load_yaml(_synthesized(context))
    assert (
        synthesized.get("apis") == override_list
    ), f"apis is {synthesized.get('apis')!r}, expected exactly {override_list!r}"
    baseline = _load_yaml(Path("run.yaml"))
    assert (
        baseline.get("apis") != override_list
    ), "fixture and baseline agree on apis — wholesale replacement would be vacuous"


@then("the synthesized run.yaml contains ${{env.OPENAI_API_KEY}}")
def synthesized_keeps_env_reference(context: Context) -> None:
    """Assert the emitted secret stays an environment reference on disk (R6)."""
    content = _synthesized(context).read_text(encoding="utf-8")
    assert (
        "${env.OPENAI_API_KEY}" in content
    ), "synthesized run.yaml does not carry the ${env.OPENAI_API_KEY} reference"


@then("the synthesized run.yaml does not contain the resolved OPENAI_API_KEY value")
def synthesized_no_literal_secret(context: Context) -> None:
    """Assert the literal secret value never lands on disk (R6)."""
    secret = os.environ.get("OPENAI_API_KEY", "")
    assert secret, (
        "OPENAI_API_KEY is not set in the harness environment — the "
        "no-literal-secret assertion would be vacuous"
    )
    content = _synthesized(context).read_text(encoding="utf-8")
    assert (
        secret not in content
    ), "synthesized run.yaml contains the resolved OPENAI_API_KEY value"


@then("the synthesized run.yaml file permissions are 0600")
def synthesized_permissions(context: Context) -> None:
    """Assert the synthesized file is owner-read/write only (R10)."""
    mode = stat.S_IMODE(os.stat(_synthesized(context)).st_mode)
    assert mode == 0o600, f"synthesized run.yaml mode is {oct(mode)}, expected 0o600"


